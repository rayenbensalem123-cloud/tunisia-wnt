export type TranslationKey = keyof typeof t.en
export type NestedKey<T, Prefix extends string = ""> = {
  [K in keyof T & string]: T[K] extends Record<string, unknown>
    ? NestedKey<T[K], `${Prefix}${K}.`>
    : `${Prefix}${K}`
}[keyof T & string]

export type TKey = NestedKey<typeof t.en>

// `t` is declared with `as const`, so each language's object has its own precise
// string-literal types (e.g. en's lang.dir is exactly "ltr", ar's is exactly "rtl").
// That makes `typeof t.en` too narrow to hold any language's data — widen every
// string literal to `string` so `t.en`, `t.fr` and `t.ar` are all assignable to it.
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
  ? Widen<U>[]
  : T extends object
  ? { [K in keyof T]: Widen<T[K]> }
  : T
export type Translations = Widen<typeof t.en>

export default t
