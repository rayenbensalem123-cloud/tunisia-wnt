-- ============================================================
-- 0012  LIGUE FEMININE  (club teams, club accounts, scoped access)
--
-- Adds a fourth category next to SENIORS / U20 / U17:
--   * league_teams       one row per club (name + logo)
--   * members.league_team_id   which club a Ligue player belongs to
--   * profiles.role 'club'     a login that is tied to ONE club
--   * profiles.league_team_id  which club that login belongs to
--
-- Who sees what:
--   admin           every club and every Ligue player
--   club account    ONLY its own club row and its own players; it can
--                   add and edit them, not delete them
--   everyone else   no Ligue data at all (staff, players, anonymous)
--
-- A club account is an outside organisation, so it must read nothing of the
-- national-team data. Almost every table gates reads with is_active_user()
-- or current_active_user(); making both return false for role 'club' shuts a
-- club out of all of them at once, and the club gets its own narrow policies
-- below instead.
--
-- Safe to re-run.
-- ============================================================

-- ------------------------------------------------------------
-- 1. TABLE + COLUMNS
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.league_teams (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL CHECK (length(btrim(name)) BETWEEN 2 AND 80),
  logo_path   text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  uuid
);
CREATE UNIQUE INDEX IF NOT EXISTS league_teams_name_key ON public.league_teams (lower(btrim(name)));

ALTER TABLE public.members  ADD COLUMN IF NOT EXISTS league_team_id bigint;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS league_team_id bigint;

-- RESTRICT, not CASCADE: deleting a club must never silently delete players.
DO $fk$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'members_league_team_id_fkey') THEN
    ALTER TABLE public.members ADD CONSTRAINT members_league_team_id_fkey
      FOREIGN KEY (league_team_id) REFERENCES public.league_teams(id) ON DELETE RESTRICT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'profiles_league_team_id_fkey') THEN
    ALTER TABLE public.profiles ADD CONSTRAINT profiles_league_team_id_fkey
      FOREIGN KEY (league_team_id) REFERENCES public.league_teams(id) ON DELETE SET NULL;
  END IF;
END $fk$;
CREATE INDEX IF NOT EXISTS members_league_team_id_idx  ON public.members(league_team_id);
CREATE INDEX IF NOT EXISTS profiles_league_team_id_idx ON public.profiles(league_team_id);

-- A Ligue player belongs to a club; nobody else has a club.
ALTER TABLE public.members DROP CONSTRAINT IF EXISTS members_league_consistency;
ALTER TABLE public.members ADD CONSTRAINT members_league_consistency
  CHECK ((team_category = 'LIGUE') = (league_team_id IS NOT NULL)) NOT VALID;

-- New role.
ALTER TABLE public.profiles DROP CONSTRAINT IF EXISTS profiles_role_check;
ALTER TABLE public.profiles ADD CONSTRAINT profiles_role_check
  CHECK (role IN ('admin','staff','player','club')) NOT VALID;

-- ------------------------------------------------------------
-- 2. HELPERS
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.my_league_team_id()
RETURNS bigint
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT league_team_id FROM profiles
  WHERE id = auth.uid() AND role = 'club' AND status = 'active';
$$;

-- Club accounts are NOT "active users" for the rest of the app.
CREATE OR REPLACE FUNCTION public.is_active_user()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND status = 'active' AND role <> 'club'
  );
$$;

CREATE OR REPLACE FUNCTION public.current_active_user()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT coalesce((
    SELECT status = 'active' AND role <> 'club' FROM profiles WHERE id = auth.uid()
  ), false);
$$;

-- ------------------------------------------------------------
-- 3. PROFILE GUARDS: nobody may point their own login at another club,
--    and self-registration can never create a club account.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.guard_profile_privileges()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF public.current_active_admin() OR auth.uid() IS NULL THEN
    RETURN NEW;
  END IF;

  IF current_setting('app.card_claim', true) = 'on'
     AND OLD.member_id IS NULL
     AND NEW.role IS NOT DISTINCT FROM OLD.role
     AND NEW.status IS NOT DISTINCT FROM OLD.status
     AND NEW.permissions IS NOT DISTINCT FROM OLD.permissions
     AND NEW.username IS NOT DISTINCT FROM OLD.username
     AND NEW.league_team_id IS NOT DISTINCT FROM OLD.league_team_id THEN
    RETURN NEW;
  END IF;

  IF NEW.role IS DISTINCT FROM OLD.role
     OR NEW.status IS DISTINCT FROM OLD.status
     OR NEW.permissions IS DISTINCT FROM OLD.permissions
     OR NEW.username IS DISTINCT FROM OLD.username
     OR NEW.member_id IS DISTINCT FROM OLD.member_id
     OR NEW.league_team_id IS DISTINCT FROM OLD.league_team_id THEN
    RAISE EXCEPTION 'Only an active admin can change role, status, permissions, username, linked player or club'
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.guard_profile_insert()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF public.current_active_admin() THEN
    RETURN NEW;  -- admins may create accounts in any state
  END IF;
  NEW.status         := 'pending';
  NEW.permissions    := '{}'::jsonb;
  NEW.league_team_id := NULL;
  IF NEW.role NOT IN ('staff','player') THEN
    NEW.role := 'player';
  END IF;
  RETURN NEW;
END;
$$;

-- ------------------------------------------------------------
-- 4. league_teams: RLS
-- ------------------------------------------------------------
ALTER TABLE public.league_teams ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS league_teams_select ON public.league_teams;
CREATE POLICY league_teams_select ON public.league_teams
  FOR SELECT TO authenticated
  USING (public.is_admin() OR id = public.my_league_team_id());

DROP POLICY IF EXISTS league_teams_admin_write ON public.league_teams;
CREATE POLICY league_teams_admin_write ON public.league_teams
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

-- ------------------------------------------------------------
-- 5. members: RLS
--    The two old "any active account reads everything" policies are replaced
--    by one that hides Ligue rows from everybody except admin and the owning
--    club. Everything else behaves exactly as before.
-- ------------------------------------------------------------
DROP POLICY IF EXISTS members_select_active        ON public.members;
DROP POLICY IF EXISTS members_select_active_users  ON public.members;
DROP POLICY IF EXISTS members_select_scoped        ON public.members;
CREATE POLICY members_select_scoped ON public.members
  FOR SELECT TO authenticated
  USING (
    (public.is_active_user() AND (team_category IS DISTINCT FROM 'LIGUE' OR public.is_admin()))
    OR (team_category = 'LIGUE' AND league_team_id IS NOT NULL AND league_team_id = public.my_league_team_id())
  );

DROP POLICY IF EXISTS members_club_insert ON public.members;
CREATE POLICY members_club_insert ON public.members
  FOR INSERT TO authenticated
  WITH CHECK (
    team_category = 'LIGUE' AND role = 'PLAYERS'
    AND league_team_id IS NOT NULL AND league_team_id = public.my_league_team_id()
  );

DROP POLICY IF EXISTS members_club_update ON public.members;
CREATE POLICY members_club_update ON public.members
  FOR UPDATE TO authenticated
  USING (team_category = 'LIGUE' AND league_team_id = public.my_league_team_id())
  WITH CHECK (
    team_category = 'LIGUE' AND role = 'PLAYERS'
    AND league_team_id = public.my_league_team_id()
  );
-- No club DELETE policy on purpose: only admins remove players.

-- The anonymous roster view must never expose Ligue players (some may be minors).
CREATE OR REPLACE VIEW public.squad_public AS
  SELECT id, legacy_id, role, name, "position", team_category, club, foot, nationality,
         languages, birthdate, height, goals, assists, clean_sheets, yellow_cards, red_cards,
         suspended, contract, nat_matches, history, image_url, image_path, jersey_number,
         camps, bio_quote, league_region, dual_nationality, second_nationality, updated_at
  FROM public.members
  WHERE team_category IS DISTINCT FROM 'LIGUE';

-- ------------------------------------------------------------
-- 6. STORAGE: a club reads/writes only league/<its team id>/...
--    (admins already pass the existing policies through has_permission)
--    Team logos live under league/logos/ and any club may read them.
-- ------------------------------------------------------------
DROP POLICY IF EXISTS league_club_read ON storage.objects;
CREATE POLICY league_club_read ON storage.objects
  FOR SELECT TO authenticated
  USING (
    bucket_id = 'members' AND public.my_league_team_id() IS NOT NULL
    AND (name LIKE 'league/logos/%' OR name LIKE 'league/' || public.my_league_team_id()::text || '/%')
  );

DROP POLICY IF EXISTS league_club_insert ON storage.objects;
CREATE POLICY league_club_insert ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id = 'members' AND public.my_league_team_id() IS NOT NULL
    AND name LIKE 'league/' || public.my_league_team_id()::text || '/%'
  );

