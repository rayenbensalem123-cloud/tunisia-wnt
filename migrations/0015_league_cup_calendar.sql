ALTER TABLE public.league_seasons ADD COLUMN IF NOT EXISTS cup_name text;
ALTER TABLE public.league_seasons ADD COLUMN IF NOT EXISTS cup_info text;
ALTER TABLE public.league_seasons DROP CONSTRAINT IF EXISTS league_seasons_cup_text_check;
ALTER TABLE public.league_seasons ADD CONSTRAINT league_seasons_cup_text_check
  CHECK ((cup_name IS NULL OR length(cup_name) <= 80) AND (cup_info IS NULL OR length(cup_info) <= 1000));

-- ------------------------------------------------------------
-- Cup matches. "round" is the number of clubs left in that round:
-- 64, 32, 16 (round of 16), 8 (quarter-finals), 4 (semi-finals), 2 (final).
-- A club can be unknown (null) while the earlier round is still being played.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.league_cup_matches (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id     bigint NOT NULL REFERENCES public.league_seasons(id) ON DELETE CASCADE,
  round         integer NOT NULL CHECK (round IN (2, 4, 8, 16, 32, 64)),
  slot          integer NOT NULL CHECK (slot BETWEEN 1 AND 32),
  home_team_id  bigint REFERENCES public.league_teams(id) ON DELETE RESTRICT,
  away_team_id  bigint REFERENCES public.league_teams(id) ON DELETE RESTRICT,
  kickoff       timestamptz,
  venue         text CHECK (venue IS NULL OR length(venue) <= 120),
  status        text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','played','postponed')),
  home_goals    integer CHECK (home_goals IS NULL OR home_goals BETWEEN 0 AND 99),
  away_goals    integer CHECK (away_goals IS NULL OR away_goals BETWEEN 0 AND 99),
  home_pens     integer CHECK (home_pens IS NULL OR home_pens BETWEEN 0 AND 99),
  away_pens     integer CHECK (away_pens IS NULL OR away_pens BETWEEN 0 AND 99),
  created_at    timestamptz NOT NULL DEFAULT now(),
  created_by    uuid,
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CHECK (home_team_id IS NULL OR away_team_id IS NULL OR home_team_id <> away_team_id),
  CHECK (slot <= round / 2),
  -- a played match has both clubs and a score; anything else has no score
  CHECK ((status = 'played') = (home_goals IS NOT NULL AND away_goals IS NOT NULL)),
  CHECK ((home_goals IS NULL) = (away_goals IS NULL)),
  CHECK (status <> 'played' OR (home_team_id IS NOT NULL AND away_team_id IS NOT NULL)),
  -- penalties only after a draw, always as a pair
  CHECK ((home_pens IS NULL) = (away_pens IS NULL)),
  CHECK (home_pens IS NULL OR (status = 'played' AND home_goals = away_goals AND home_pens <> away_pens))
);
CREATE UNIQUE INDEX IF NOT EXISTS league_cup_matches_slot_key ON public.league_cup_matches (season_id, round, slot);
CREATE INDEX IF NOT EXISTS league_cup_matches_season_idx ON public.league_cup_matches (season_id, round DESC, slot);

CREATE TABLE IF NOT EXISTS public.league_breaks (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id   bigint NOT NULL REFERENCES public.league_seasons(id) ON DELETE CASCADE,
  title       text NOT NULL CHECK (length(btrim(title)) BETWEEN 2 AND 80),
  starts_on   date NOT NULL,
  ends_on     date NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  uuid,
  CHECK (starts_on <= ends_on)
);
CREATE INDEX IF NOT EXISTS league_breaks_season_idx ON public.league_breaks (season_id, starts_on);

-- ------------------------------------------------------------
-- RLS
-- ------------------------------------------------------------
ALTER TABLE public.league_cup_matches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.league_breaks      ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS league_cup_matches_read ON public.league_cup_matches;
CREATE POLICY league_cup_matches_read ON public.league_cup_matches
  FOR SELECT TO authenticated
  USING (public.is_admin() OR public.my_league_team_id() IS NOT NULL);
DROP POLICY IF EXISTS league_cup_matches_admin_write ON public.league_cup_matches;
CREATE POLICY league_cup_matches_admin_write ON public.league_cup_matches
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS league_breaks_read ON public.league_breaks;
CREATE POLICY league_breaks_read ON public.league_breaks
  FOR SELECT TO authenticated
  USING (public.is_admin() OR public.my_league_team_id() IS NOT NULL);
DROP POLICY IF EXISTS league_breaks_admin_write ON public.league_breaks;
CREATE POLICY league_breaks_admin_write ON public.league_breaks
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

REVOKE ALL ON public.league_cup_matches FROM anon;
REVOKE ALL ON public.league_breaks      FROM anon;

