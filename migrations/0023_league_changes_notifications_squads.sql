-- ============================================================
-- 0023  LIGUE FEMININE: MATCH CHANGE HISTORY, CLUB NOTIFICATIONS, MATCHDAY SQUADS
--
--   * league_fixtures.change_note   optional reason typed by the admin with an edit
--   * league_fixture_changes        every change of date or status (history shown on the match)
--   * league_notifications          one row per club per change, read by that club only
--   * league_match_squad            the players a club names for an upcoming match
--
-- Access
--   history          admin and every club account read it; only the trigger writes it
--   notifications    a club reads and marks read only its own; the trigger writes them
--   squads           a club reads, adds and removes only its own club's squad, until the
--                    match is played; admin reads every squad and may edit them
--
-- Depends on 0012, 0015 and 0020 (0021 and 0022 change how stats are counted; this file does not touch them) (its trigger function league_sheet_fill is reused).
-- Safe to re-run.
-- ============================================================

ALTER TABLE public.league_fixtures ADD COLUMN IF NOT EXISTS change_note text;
ALTER TABLE public.league_fixtures DROP CONSTRAINT IF EXISTS league_fixtures_change_note_check;
ALTER TABLE public.league_fixtures ADD CONSTRAINT league_fixtures_change_note_check
  CHECK (change_note IS NULL OR length(change_note) <= 200);

-- ------------------------------------------------------------
-- History
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.league_fixture_changes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_id  bigint NOT NULL REFERENCES public.league_fixtures(id) ON DELETE CASCADE,
  season_id   bigint NOT NULL REFERENCES public.league_seasons(id)  ON DELETE CASCADE,
  old_kickoff timestamptz,
  new_kickoff timestamptz,
  old_status  text NOT NULL,
  new_status  text NOT NULL,
  note        text,
  changed_at  timestamptz NOT NULL DEFAULT now(),
  changed_by  uuid
);
CREATE INDEX IF NOT EXISTS league_fixture_changes_fixture_idx ON public.league_fixture_changes (fixture_id, changed_at);

-- ------------------------------------------------------------
-- Notifications
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.league_notifications (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id     bigint NOT NULL REFERENCES public.league_teams(id)    ON DELETE CASCADE,
  fixture_id  bigint NOT NULL REFERENCES public.league_fixtures(id) ON DELETE CASCADE,
  kind        text NOT NULL CHECK (kind IN ('scheduled','moved','postponed','result')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  read_at     timestamptz
);
CREATE INDEX IF NOT EXISTS league_notifications_team_idx ON public.league_notifications (team_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.league_fixture_track()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE k text;
BEGIN
  IF NEW.kickoff IS NOT DISTINCT FROM OLD.kickoff AND NEW.status = OLD.status THEN RETURN NEW; END IF;
  INSERT INTO public.league_fixture_changes (fixture_id, season_id, old_kickoff, new_kickoff, old_status, new_status, note, changed_by)
  VALUES (NEW.id, NEW.season_id, OLD.kickoff, NEW.kickoff, OLD.status, NEW.status, NULLIF(btrim(NEW.change_note), ''), auth.uid());
  k := CASE
    WHEN NEW.status = 'played' AND OLD.status <> 'played' THEN 'result'
    WHEN NEW.status = 'postponed' AND OLD.status <> 'postponed' THEN 'postponed'
    WHEN NEW.status = 'scheduled' AND NEW.kickoff IS NOT NULL AND OLD.kickoff IS NULL THEN 'scheduled'
    WHEN NEW.status = 'scheduled' AND NEW.kickoff IS NOT NULL AND OLD.kickoff IS DISTINCT FROM NEW.kickoff THEN 'moved'
    ELSE NULL END;
  IF k IS NOT NULL THEN
    INSERT INTO public.league_notifications (team_id, fixture_id, kind)
    VALUES (NEW.home_team_id, NEW.id, k), (NEW.away_team_id, NEW.id, k);
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_league_fixture_track ON public.league_fixtures;
CREATE TRIGGER trg_league_fixture_track AFTER UPDATE ON public.league_fixtures
  FOR EACH ROW EXECUTE FUNCTION public.league_fixture_track();

-- ------------------------------------------------------------
-- Squads
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.league_match_squad (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_id  bigint NOT NULL REFERENCES public.league_fixtures(id) ON DELETE CASCADE,
  season_id   bigint NOT NULL REFERENCES public.league_seasons(id)  ON DELETE CASCADE,
  team_id     bigint NOT NULL REFERENCES public.league_teams(id)    ON DELETE CASCADE,
  member_id   bigint NOT NULL REFERENCES public.members(id)         ON DELETE CASCADE,
  player_name text   NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  uuid
);
CREATE UNIQUE INDEX IF NOT EXISTS league_match_squad_key ON public.league_match_squad (fixture_id, member_id);
CREATE INDEX IF NOT EXISTS league_match_squad_team_idx ON public.league_match_squad (fixture_id, team_id);

DROP TRIGGER IF EXISTS trg_league_match_squad_fill ON public.league_match_squad;
CREATE TRIGGER trg_league_match_squad_fill BEFORE INSERT OR UPDATE ON public.league_match_squad
  FOR EACH ROW EXECUTE FUNCTION public.league_sheet_fill();

-- a squad can no longer change once the match is played
CREATE OR REPLACE FUNCTION public.league_squad_open(p_fixture bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT EXISTS (SELECT 1 FROM public.league_fixtures WHERE id = p_fixture AND status <> 'played')
$$;
REVOKE ALL ON FUNCTION public.league_squad_open(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.league_squad_open(bigint) TO authenticated;

-- ------------------------------------------------------------
-- RLS
-- ------------------------------------------------------------
ALTER TABLE public.league_fixture_changes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.league_notifications   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.league_match_squad     ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS league_fixture_changes_read ON public.league_fixture_changes;
CREATE POLICY league_fixture_changes_read ON public.league_fixture_changes
  FOR SELECT TO authenticated USING (public.is_admin() OR public.my_league_team_id() IS NOT NULL);
DROP POLICY IF EXISTS league_fixture_changes_admin_write ON public.league_fixture_changes;
CREATE POLICY league_fixture_changes_admin_write ON public.league_fixture_changes
  FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS league_notifications_read ON public.league_notifications;
CREATE POLICY league_notifications_read ON public.league_notifications
  FOR SELECT TO authenticated USING (team_id = public.my_league_team_id() OR public.is_admin());
DROP POLICY IF EXISTS league_notifications_mark ON public.league_notifications;
CREATE POLICY league_notifications_mark ON public.league_notifications
  FOR UPDATE TO authenticated USING (team_id = public.my_league_team_id()) WITH CHECK (team_id = public.my_league_team_id());
DROP POLICY IF EXISTS league_notifications_admin_write ON public.league_notifications;
CREATE POLICY league_notifications_admin_write ON public.league_notifications
  FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS league_match_squad_read ON public.league_match_squad;
CREATE POLICY league_match_squad_read ON public.league_match_squad
  FOR SELECT TO authenticated USING (public.is_admin() OR team_id = public.my_league_team_id());
DROP POLICY IF EXISTS league_match_squad_club_write ON public.league_match_squad;
CREATE POLICY league_match_squad_club_write ON public.league_match_squad
  FOR INSERT TO authenticated WITH CHECK (team_id = public.my_league_team_id() AND public.league_squad_open(fixture_id));
DROP POLICY IF EXISTS league_match_squad_club_delete ON public.league_match_squad;
CREATE POLICY league_match_squad_club_delete ON public.league_match_squad
  FOR DELETE TO authenticated USING (team_id = public.my_league_team_id() AND public.league_squad_open(fixture_id));
DROP POLICY IF EXISTS league_match_squad_admin_write ON public.league_match_squad;
CREATE POLICY league_match_squad_admin_write ON public.league_match_squad
  FOR ALL TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

REVOKE ALL ON public.league_fixture_changes FROM anon;
REVOKE ALL ON public.league_notifications   FROM anon;
REVOKE ALL ON public.league_match_squad     FROM anon;
GRANT SELECT ON public.league_fixture_changes TO authenticated;
GRANT INSERT, DELETE ON public.league_fixture_changes TO authenticated; -- admin only through the policy
GRANT SELECT, INSERT, DELETE ON public.league_notifications TO authenticated;
GRANT UPDATE (read_at) ON public.league_notifications TO authenticated;  -- a club can only mark read
GRANT SELECT, INSERT, DELETE ON public.league_match_squad TO authenticated;
