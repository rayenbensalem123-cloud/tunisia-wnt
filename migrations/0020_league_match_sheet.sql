-- ============================================================
-- 0020  LIGUE FEMININE: MATCH SHEET (lineups and match events)
--
--   * league_match_lineup   who played in a match (one row per player per match)
--   * league_match_events   goals, assists, yellow and red cards, with the minute
--
-- Both tables copy the player's name when the row is written, so a club account can read
-- the whole league's match sheets without being able to read other clubs' member rows.
--
-- league_player_stats (0018) is kept up to date from these tables: for every player who has
-- a match sheet row, her season line is recounted from the sheets. Players with no sheet
-- keep whatever totals an admin typed by hand.
--
--   admin           read and write
--   club account    READ ONLY, the whole league
--   everyone else   nothing
--
-- Depends on 0012, 0015 and 0018. Safe to re-run.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.league_match_lineup (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_id  bigint NOT NULL REFERENCES public.league_fixtures(id) ON DELETE CASCADE,
  season_id   bigint NOT NULL REFERENCES public.league_seasons(id)  ON DELETE CASCADE,
  team_id     bigint NOT NULL REFERENCES public.league_teams(id)    ON DELETE CASCADE,
  member_id   bigint NOT NULL REFERENCES public.members(id)         ON DELETE CASCADE,
  player_name text   NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  uuid
);
CREATE UNIQUE INDEX IF NOT EXISTS league_match_lineup_key ON public.league_match_lineup (fixture_id, member_id);
CREATE INDEX IF NOT EXISTS league_match_lineup_season_idx ON public.league_match_lineup (season_id, member_id);

CREATE TABLE IF NOT EXISTS public.league_match_events (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fixture_id  bigint NOT NULL REFERENCES public.league_fixtures(id) ON DELETE CASCADE,
  season_id   bigint NOT NULL REFERENCES public.league_seasons(id)  ON DELETE CASCADE,
  team_id     bigint NOT NULL REFERENCES public.league_teams(id)    ON DELETE CASCADE,
  member_id   bigint NOT NULL REFERENCES public.members(id)         ON DELETE CASCADE,
  player_name text   NOT NULL,
  kind        text   NOT NULL CHECK (kind IN ('goal','assist','yellow','red')),
  minute      integer CHECK (minute IS NULL OR minute BETWEEN 0 AND 130),
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  uuid
);
CREATE INDEX IF NOT EXISTS league_match_events_fixture_idx ON public.league_match_events (fixture_id, minute);
CREATE INDEX IF NOT EXISTS league_match_events_season_idx  ON public.league_match_events (season_id, member_id, kind);

-- ------------------------------------------------------------
-- Fill season_id and player_name, and refuse rows that do not make sense:
-- the club must be one of the two clubs of the match and the player must belong to that club.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.league_sheet_fill()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE f public.league_fixtures%ROWTYPE; m public.members%ROWTYPE;
BEGIN
  SELECT * INTO f FROM public.league_fixtures WHERE id = NEW.fixture_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'unknown fixture' USING ERRCODE = '23503'; END IF;
  IF NEW.team_id NOT IN (f.home_team_id, f.away_team_id) THEN
    RAISE EXCEPTION 'club is not part of this match' USING ERRCODE = '23514';
  END IF;
  SELECT * INTO m FROM public.members WHERE id = NEW.member_id;
  IF NOT FOUND OR m.league_team_id IS DISTINCT FROM NEW.team_id THEN
    RAISE EXCEPTION 'player does not belong to this club' USING ERRCODE = '23514';
  END IF;
  NEW.season_id   := f.season_id;
  NEW.player_name := m.name;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_league_match_lineup_fill ON public.league_match_lineup;
CREATE TRIGGER trg_league_match_lineup_fill BEFORE INSERT OR UPDATE ON public.league_match_lineup
  FOR EACH ROW EXECUTE FUNCTION public.league_sheet_fill();
DROP TRIGGER IF EXISTS trg_league_match_events_fill ON public.league_match_events;
CREATE TRIGGER trg_league_match_events_fill BEFORE INSERT OR UPDATE ON public.league_match_events
  FOR EACH ROW EXECUTE FUNCTION public.league_sheet_fill();

-- ------------------------------------------------------------
-- Keep league_player_stats in step with the sheets
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.league_recount_player(p_season bigint, p_member bigint)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE a int; g int; s int; y int; r int;
BEGIN
  IF p_season IS NULL OR p_member IS NULL THEN RETURN; END IF;
  SELECT count(*) INTO a FROM public.league_match_lineup WHERE season_id = p_season AND member_id = p_member;
  SELECT count(*) FILTER (WHERE kind = 'goal'),   count(*) FILTER (WHERE kind = 'assist'),
         count(*) FILTER (WHERE kind = 'yellow'), count(*) FILTER (WHERE kind = 'red')
    INTO g, s, y, r FROM public.league_match_events WHERE season_id = p_season AND member_id = p_member;
  IF a = 0 AND g = 0 AND s = 0 AND y = 0 AND r = 0 THEN RETURN; END IF; -- no sheet row left: keep hand-typed totals
  INSERT INTO public.league_player_stats (season_id, member_id, appearances, goals, assists, yellows, reds, updated_at)
  VALUES (p_season, p_member, a, g, s, y, r, now())
  ON CONFLICT (season_id, member_id) DO UPDATE
    SET appearances = EXCLUDED.appearances, goals = EXCLUDED.goals, assists = EXCLUDED.assists,
        yellows = EXCLUDED.yellows, reds = EXCLUDED.reds, updated_at = now();
END $$;

CREATE OR REPLACE FUNCTION public.league_sheet_recount()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
  IF TG_OP IN ('UPDATE','DELETE') THEN PERFORM public.league_recount_player(OLD.season_id, OLD.member_id); END IF;
  IF TG_OP IN ('INSERT','UPDATE') THEN PERFORM public.league_recount_player(NEW.season_id, NEW.member_id); END IF;
  RETURN COALESCE(NEW, OLD);
END $$;

DROP TRIGGER IF EXISTS trg_league_match_lineup_recount ON public.league_match_lineup;
CREATE TRIGGER trg_league_match_lineup_recount AFTER INSERT OR UPDATE OR DELETE ON public.league_match_lineup
  FOR EACH ROW EXECUTE FUNCTION public.league_sheet_recount();
DROP TRIGGER IF EXISTS trg_league_match_events_recount ON public.league_match_events;
CREATE TRIGGER trg_league_match_events_recount AFTER INSERT OR UPDATE OR DELETE ON public.league_match_events
  FOR EACH ROW EXECUTE FUNCTION public.league_sheet_recount();

