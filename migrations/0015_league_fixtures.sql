-- ============================================================
-- 0015  LIGUE FEMININE: SEASONS, MATCHDAYS AND RESULTS
--
--   * league_seasons    one row per season (2026/27, 2027/28 ...), one is "current"
--   * league_fixtures   one row per match: season, matchday, home/away club,
--                       kick-off, venue, status and score
--
-- Who can do what:
--   admin           read and write everything
--   club account    READ ONLY, the whole league's fixtures (not just its own)
--   everyone else   nothing (staff, players, anonymous)
--
-- Depends on 0012 (league_teams, my_league_team_id, is_admin).
-- Safe to re-run.
-- ============================================================

-- ------------------------------------------------------------
-- 1. TABLES
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.league_seasons (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL CHECK (length(btrim(name)) BETWEEN 2 AND 40),
  starts_on   date,
  ends_on     date,
  is_current  boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  uuid,
  CHECK (starts_on IS NULL OR ends_on IS NULL OR starts_on <= ends_on)
);
CREATE UNIQUE INDEX IF NOT EXISTS league_seasons_name_key ON public.league_seasons (lower(btrim(name)));
-- at most one current season
CREATE UNIQUE INDEX IF NOT EXISTS league_seasons_one_current ON public.league_seasons (is_current) WHERE is_current;

CREATE TABLE IF NOT EXISTS public.league_fixtures (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id     bigint NOT NULL REFERENCES public.league_seasons(id) ON DELETE CASCADE,
  matchday      integer NOT NULL CHECK (matchday BETWEEN 1 AND 99),
  home_team_id  bigint NOT NULL REFERENCES public.league_teams(id) ON DELETE RESTRICT,
  away_team_id  bigint NOT NULL REFERENCES public.league_teams(id) ON DELETE RESTRICT,
  kickoff       timestamptz,
  venue         text CHECK (venue IS NULL OR length(venue) <= 120),
  status        text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','played','postponed')),
  home_goals    integer CHECK (home_goals IS NULL OR home_goals BETWEEN 0 AND 99),
  away_goals    integer CHECK (away_goals IS NULL OR away_goals BETWEEN 0 AND 99),
  created_at    timestamptz NOT NULL DEFAULT now(),
  created_by    uuid,
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CHECK (home_team_id <> away_team_id),
  -- a played match has a score, any other status has none
  CHECK ((status = 'played') = (home_goals IS NOT NULL AND away_goals IS NOT NULL)),
  CHECK ((home_goals IS NULL) = (away_goals IS NULL))
);
-- a club plays at most once per matchday in a season
CREATE UNIQUE INDEX IF NOT EXISTS league_fixtures_home_once ON public.league_fixtures (season_id, matchday, home_team_id);
CREATE UNIQUE INDEX IF NOT EXISTS league_fixtures_away_once ON public.league_fixtures (season_id, matchday, away_team_id);
CREATE INDEX IF NOT EXISTS league_fixtures_season_idx ON public.league_fixtures (season_id, matchday, kickoff);

-- ------------------------------------------------------------
-- 2. RLS: club accounts and admins read, only admins write
-- ------------------------------------------------------------
ALTER TABLE public.league_seasons  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.league_fixtures ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS league_seasons_read ON public.league_seasons;
CREATE POLICY league_seasons_read ON public.league_seasons
  FOR SELECT TO authenticated
  USING (public.is_admin() OR public.my_league_team_id() IS NOT NULL);

DROP POLICY IF EXISTS league_seasons_admin_write ON public.league_seasons;
CREATE POLICY league_seasons_admin_write ON public.league_seasons
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS league_fixtures_read ON public.league_fixtures;
CREATE POLICY league_fixtures_read ON public.league_fixtures
  FOR SELECT TO authenticated
  USING (public.is_admin() OR public.my_league_team_id() IS NOT NULL);

DROP POLICY IF EXISTS league_fixtures_admin_write ON public.league_fixtures;
CREATE POLICY league_fixtures_admin_write ON public.league_fixtures
  FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

REVOKE ALL ON public.league_seasons  FROM anon;
REVOKE ALL ON public.league_fixtures FROM anon;

-- Switch the current season in one transaction (the unique index forbids two at once).
-- SECURITY INVOKER on purpose: RLS then makes it admin-only.
CREATE OR REPLACE FUNCTION public.league_set_current_season(p_id bigint)
RETURNS void
LANGUAGE plpgsql SET search_path = public
AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.league_seasons WHERE id = p_id) THEN
    RAISE EXCEPTION 'Season not found';
  END IF;
  UPDATE public.league_seasons SET is_current = false WHERE is_current AND id <> p_id;
  UPDATE public.league_seasons SET is_current = true  WHERE id = p_id;
END;
$$;
REVOKE ALL ON FUNCTION public.league_set_current_season(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.league_set_current_season(bigint) TO authenticated;

-- A club account must be able to name the OTHER clubs in the fixtures list.
-- league_teams is readable only for its own row (0012), so expose just id, name
-- and logo of every club through a narrow view that runs with owner rights.
CREATE OR REPLACE FUNCTION public.league_club_directory()
RETURNS TABLE (id bigint, name text, logo_path text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT t.id, t.name, t.logo_path
  FROM public.league_teams t
  WHERE public.is_admin() OR public.my_league_team_id() IS NOT NULL
  ORDER BY t.name;
$$;
REVOKE ALL ON FUNCTION public.league_club_directory() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.league_club_directory() TO authenticated;

-- ------------------------------------------------------------
-- 3. updated_at + AUDIT
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.league_fixtures_touch()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_league_fixtures_touch ON public.league_fixtures;
CREATE TRIGGER trg_league_fixtures_touch BEFORE UPDATE ON public.league_fixtures
  FOR EACH ROW EXECUTE FUNCTION public.league_fixtures_touch();

